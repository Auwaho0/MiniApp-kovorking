export type TimeSlot = {
  /** Уникальный идентификатор — используется как ключ */
  id: string;
  /** "HH:MM" — начало */
  start: string;
  /** "HH:MM" — конец */
  end: string;
  /** Что видит пользователь */
  label: string;
};

